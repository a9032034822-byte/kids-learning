export function t(lang, key, gender) {
  const v = (S[lang] && S[lang][key]) ?? S.ru[key] ?? key;
  if (v && typeof v === 'object' && !Array.isArray(v)) return v[gender === 'f' ? 'f' : 'm'];
  return v;
}

export function ui(lang, key) {
  return (UI[lang] && UI[lang][key]) ?? UI.ru[key] ?? key;
}

export function praise(lang, gender) {
  const arr = t(lang, gender === 'f' ? 'greatF' : 'great');
  return arr[Math.floor(Math.random() * arr.length)];
}

